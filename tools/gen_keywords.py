#!/usr/bin/env python3
"""
gen_keywords.py - writes keywords.txt (Arduino IDE syntax highlighting) from src/eccles_gui.h

  python3 tools/gen_keywords.py            rewrite keywords.txt
  python3 tools/gen_keywords.py --check    fail if it is stale
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HDR = os.path.join(HERE, "..", "src", "eccles_gui.h")
OUT = os.path.join(HERE, "..", "keywords.txt")


def main():
    h = open(HDR, encoding="utf-8").read()
    types = sorted(set(re.findall(r"\}\s*(eccles_gui_\w+_t)\s*;", h)) | set(re.findall(r"typedef\s+\w+\s+(eccles_gui_\w+_t)\s*;", h))
                   | set(re.findall(r"typedef\s+[^;{]*?\(\*(eccles_gui_\w+_fn)\)", h)))
    funcs = sorted(set(re.findall(r"\b(eccles_gui_[a-z0-9_]+)\s*\(", h)) - set(types))
    consts = sorted(set(re.findall(r"#define\s+(ECCLES_GUI_[A-Z0-9_]+)", h)) | set(re.findall(r"^\s+(ECCLES_GUI_[A-Z0-9_]+)\s*(?:=|,|$)", h, re.M)))
    consts = [c for c in consts if not c.endswith("_H") and not c.startswith("ECCLES_GUI_HAS_")]
    lines = ["# keywords.txt for the Arduino IDE (generated by tools/gen_keywords.py)", "", "# types"]
    lines += ["%s\tKEYWORD1" % t for t in types]
    lines += ["", "# functions"]
    lines += ["%s\tKEYWORD2" % f for f in funcs if f not in types]
    lines += ["", "# constants and macros"]
    lines += ["%s\tLITERAL1" % c for c in consts]
    text = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("keywords.txt is stale: run python3 tools/gen_keywords.py")
            sys.exit(1)
        print("keywords.txt up to date")
        return
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("keywords.txt written: %d types, %d functions, %d constants" % (len(types), len(funcs), len(consts)))


if __name__ == "__main__":
    main()
