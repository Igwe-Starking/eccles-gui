#!/usr/bin/env python3
"""
ttf2eccles_font.py - turn a TrueType/OpenType font into an anti aliased eccles_gui font (needs Pillow)

  python3 tools/ttf2eccles_font.py MyFont.ttf --size 24 --bpp 4 --name font_ui24 > font_ui24.c

  --range 0x20-0x7E        codepoint ranges to include (repeatable, default ascii)
  --symbols "°•€"          extra characters
  --bpp 1|4|8              1 = hard edged, 4 = 16 gray levels (default, good), 8 = 256 levels
  --size                   pixel size of the em

then in your code:   int id = eccles_gui_font_register(&gui, &font_ui24, 1);   and use id in a style (style.font = id)
mind the font license when you ship the generated file
"""
import argparse
import sys
from PIL import Image, ImageDraw, ImageFont


def parse_range(s):
    a, _, b = s.partition("-")
    lo = int(a, 0)
    hi = int(b, 0) if b else lo
    if hi < lo:
        sys.exit("bad range " + s)
    return lo, hi


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("ttf")
    ap.add_argument("--size", type=int, default=20)
    ap.add_argument("--bpp", type=int, choices=[1, 4, 8], default=4)
    ap.add_argument("--name", default="font_custom")
    ap.add_argument("--range", action="append", default=[])
    ap.add_argument("--symbols", default="")
    ap.add_argument("--static", action="store_true")
    a = ap.parse_args()

    font = ImageFont.truetype(a.ttf, a.size)
    ascent, descent = font.getmetrics()
    cps = set()
    for r in (a.range or ["0x20-0x7E"]):
        lo, hi = parse_range(r)
        cps.update(range(lo, hi + 1))
    cps.update(ord(c) for c in a.symbols)
    cps = sorted(cps)

    glyphs, bitmap = [], bytearray()
    ranges = []  # (first, count, index)
    for cp in cps:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor="ls")  # relative to the baseline origin
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            g = (len(bitmap), 0, 0, 0, 0, adv)
        else:
            pad = 4
            im = Image.new("L", (w + 2 * pad, h + 2 * pad), 0)
            ImageDraw.Draw(im).text((pad - l, pad - t), ch, font=font, fill=255, anchor="ls")
            im = im.crop((pad, pad, pad + w, pad + h))
            off = len(bitmap)
            px = list(im.tobytes())
            for y in range(h):
                row = px[y * w:(y + 1) * w]
                if a.bpp == 8:
                    bitmap += bytes(row)
                elif a.bpp == 4:
                    q = [v >> 4 for v in row]
                    if len(q) % 2:
                        q.append(0)
                    bitmap += bytes((q[i] << 4) | q[i + 1] for i in range(0, len(q), 2))
                else:
                    q = [1 if v >= 128 else 0 for v in row]
                    while len(q) % 8:
                        q.append(0)
                    for i in range(0, len(q), 8):
                        v = 0
                        for k in range(8):
                            v |= q[i + k] << (7 - k)
                        bitmap.append(v)
            if l < -128 or l > 127 or ascent + t < -128 or ascent + t > 127 or w > 255 or h > 255:
                sys.exit("glyph %r is too big for the glyph format, use a smaller --size" % ch)
            g = (off, w, h, l, ascent + t, adv)
        if adv > 255:
            sys.exit("advance too big")
        if ranges and ranges[-1][0] + ranges[-1][1] == cp:
            ranges[-1][1] += 1
        else:
            ranges.append([cp, 1, len(glyphs)])
        glyphs.append(g)
    if len(ranges) > 255:
        sys.exit("too many ranges")

    n = a.name
    q = "static " if a.static else ""
    print("//generated by tools/ttf2eccles_font.py from %s, size %d, %d bpp, %d glyphs, %d bytes of bitmap. mind the font license" % (
        a.ttf.split("/")[-1], a.size, a.bpp, len(glyphs), len(bitmap)))
    print('#include "eccles_gui.h"\n')
    print("static const uint8_t %s_bitmap[] = {" % n)
    for i in range(0, len(bitmap), 16):
        print("    " + ", ".join("0x%02X" % v for v in bitmap[i:i + 16]) + ",")
    if not bitmap:
        print("    0")
    print("};")
    print("static const eccles_gui_glyph_t %s_glyphs[] = {" % n)
    for g in glyphs:
        print("    {%d, %d, %d, %d, %d, %d}," % g)
    print("};")
    print("static const eccles_gui_range_t %s_ranges[] = {" % n)
    for r in ranges:
        print("    {0x%X, %d, %d}," % tuple(r))
    print("};")
    print("%sconst eccles_gui_font_t %s = {%s_glyphs, %s_bitmap, %s_ranges, %d, %d, %d};" % (q, n, n, n, n, len(ranges), ascent + descent, a.bpp))


if __name__ == "__main__":
    main()
