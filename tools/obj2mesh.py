#!/usr/bin/env python3
"""
obj2mesh.py - turn a Wavefront .obj into an eccles_gui mesh (plain python 3, no dependencies)

  python3 tools/obj2mesh.py ship.obj --name ship > ship_mesh.c            smooth shading normals
  python3 tools/obj2mesh.py rock.obj --name rock --flat > rock_mesh.c     faceted look (every face gets its own vertices)

  --no-normalize   keep the coordinates (default: centered and scaled so the largest extent is +-1.0)
  --keep-z         do not flip z. by default z is flipped (obj is right handed, eccles_gui looks along +z) and the winding
                   reversed so the model looks the way it did in your modeller, seen from the front

faces with more than 3 corners are triangulated, uv comes from vt (v flipped, 0..255), normals are computed from the geometry
the converter tells you the vertex/face counts: the 3d cache holds ECCLES_GUI_3D_MAX_VERTS (192) and ECCLES_GUI_3D_MAX_FACES (256)
by default, raise them in eccles_gui_config.h for bigger models
"""
import argparse
import math
import sys


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("obj")
    ap.add_argument("--name", default="mesh")
    ap.add_argument("--flat", action="store_true")
    ap.add_argument("--no-normalize", action="store_true")
    ap.add_argument("--keep-z", action="store_true")
    a = ap.parse_args()

    V, VT, faces = [], [], []
    with open(a.obj, "r") as fh:
        for line in fh:
            t = line.split()
            if not t:
                continue
            if t[0] == "v":
                V.append(tuple(float(x) for x in t[1:4]))
            elif t[0] == "vt":
                VT.append((float(t[1]), float(t[2]) if len(t) > 2 else 0.0))
            elif t[0] == "f":
                idx = []
                for c in t[1:]:
                    p = c.split("/")
                    vi = int(p[0])
                    vi = vi - 1 if vi > 0 else len(V) + vi
                    ti = None
                    if len(p) > 1 and p[1]:
                        ti = int(p[1])
                        ti = ti - 1 if ti > 0 else len(VT) + ti
                    idx.append((vi, ti))
                for k in range(1, len(idx) - 1):
                    faces.append((idx[0], idx[k], idx[k + 1]))
    if not V or not faces:
        sys.exit("no geometry in " + a.obj)

    if not a.no_normalize:
        lo = [min(v[i] for v in V) for i in range(3)]
        hi = [max(v[i] for v in V) for i in range(3)]
        ctr = [(lo[i] + hi[i]) / 2 for i in range(3)]
        ext = max(hi[i] - lo[i] for i in range(3)) / 2 or 1.0
        V = [tuple((v[i] - ctr[i]) / ext for i in range(3)) for v in V]
    if not a.keep_z:
        V = [(v[0], v[1], -v[2]) for v in V]
        faces = [(f[0], f[2], f[1]) for f in faces]

    def sub(p, q): return (p[0] - q[0], p[1] - q[1], p[2] - q[2])
    def cross(p, q): return (p[1] * q[2] - p[2] * q[1], p[2] * q[0] - p[0] * q[2], p[0] * q[1] - p[1] * q[0])
    def norm(p):
        l = math.sqrt(p[0] ** 2 + p[1] ** 2 + p[2] ** 2)
        return (p[0] / l, p[1] / l, p[2] / l) if l > 1e-12 else (0.0, 0.0, 0.0)

    verts, vmap, vuv, tris, fn = [], {}, [], [], []
    has_uv = bool(VT)
    for fi, f in enumerate(faces):
        ids = []
        for (vi, ti) in f:
            key = (vi, ti, fi if a.flat else -1)
            if key not in vmap:
                vmap[key] = len(verts)
                verts.append(V[vi])
                if has_uv:
                    u, v = VT[ti] if ti is not None else (0.0, 0.0)
                    vuv.append((max(0, min(255, round(u * 255))), max(0, min(255, round((1 - v) * 255)))))
            ids.append(vmap[key])
        pa, pb, pc = (verts[i] for i in ids)
        n = norm(cross(sub(pb, pa), sub(pc, pa)))
        tris.append(tuple(ids))
        fn.append(n)
    vn = [[0.0, 0.0, 0.0] for _ in verts]
    for t, n in zip(tris, fn):
        for i in t:
            for k in range(3):
                vn[i][k] += n[k]
    vn = [norm(v) for v in vn]

    def q12(x):
        v = int(round(x * 4096))
        return max(-32768, min(32767, v))

    def q7(x): return max(-127, min(127, int(round(x * 127))))

    def arr(ctype, ident, vals, per=12):
        print("static const %s %s[] = {" % (ctype, ident))
        for i in range(0, len(vals), per):
            print("    " + ", ".join(str(x) for x in vals[i:i + per]) + ",")
        print("};")

    n = a.name
    print("//generated by tools/obj2mesh.py from %s: %d vertices, %d faces%s. do not edit" % (a.obj.split("/")[-1], len(verts), len(tris), ", flat" if a.flat else ""))
    print('#include "eccles_gui.h"\n')
    arr("int16_t", n + "_v", [q12(c) for p in verts for c in p])
    arr("uint16_t", n + "_f", [i for t in tris for i in t])
    arr("int8_t", n + "_n", [q7(c) for p in fn for c in p])
    arr("int8_t", n + "_vn", [q7(c) for p in vn for c in p])
    if has_uv:
        arr("uint8_t", n + "_uv", [c for u in vuv for c in u], 16)
    print("const eccles_gui_mesh_t %s = {%s_v, %s_f, %s_n, %s_vn, NULL, %s, %d, %d};" % (
        n, n, n, n, n, (n + "_uv") if has_uv else "NULL", len(verts), len(tris)))
    sys.stderr.write("%s: %d vertices, %d faces%s\n" % (n, len(verts), len(tris), "  (more than the default 3d cache: raise ECCLES_GUI_3D_MAX_VERTS/FACES)" if len(verts) > 192 or len(tris) > 256 else ""))


if __name__ == "__main__":
    main()
