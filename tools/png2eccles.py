#!/usr/bin/env python3
"""
png2eccles.py - turn a PNG into a C image for eccles_gui (needs Pillow)

  python3 tools/png2eccles.py icon.png --name icon_home --format a8 > icon_home.c

formats
  rgb565   opaque colors (transparent pixels become black)
  key      rgb565 with a color key: pixels with alpha < 128 become the key color and are skipped when drawing (--key 0xF81F)
  a8       8 bit alpha mask, painted in the color you pass to eccles_gui_draw_image (best for icons). uses the alpha channel,
           or the brightness when the png has none
  a4       4 bit alpha, half the size of a8
  a1       1 bit mask (--threshold 0..255)

the output declares   const eccles_gui_image_t <name>;   use it with eccles_gui_image_create() or eccles_gui_draw_image()
"""
import argparse
import sys
from PIL import Image


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def wrap(items, per, fmt):
    lines = []
    for i in range(0, len(items), per):
        lines.append("    " + ", ".join(fmt % v for v in items[i:i + per]) + ",")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png")
    ap.add_argument("--name", default="image")
    ap.add_argument("--format", choices=["rgb565", "key", "a8", "a4", "a1"], default="rgb565")
    ap.add_argument("--key", default="0xF81F", help="color key for --format key")
    ap.add_argument("--threshold", type=int, default=128, help="a1 threshold")
    ap.add_argument("--static", action="store_true", help="declare the image static")
    a = ap.parse_args()

    im = Image.open(a.png).convert("RGBA")
    w, h = im.size
    if w > 65535 or h > 65535:
        sys.exit("image too big")
    raw = im.tobytes()
    px = [tuple(raw[i:i + 4]) for i in range(0, len(raw), 4)]
    name = a.name
    has_alpha = any(p[3] != 255 for p in px)
    out = ["//generated by tools/png2eccles.py from %s (%s, %dx%d), do not edit" % (a.png.split("/")[-1], a.format, w, h),
           '#include "eccles_gui.h"', ""]
    key = int(a.key, 0)
    qual = "static " if a.static else ""

    if a.format in ("rgb565", "key"):
        vals = []
        for r, g, b, al in px:
            if al < 128 and a.format == "key":
                vals.append(key)
            elif al < 128:
                vals.append(0)
            else:
                v = rgb565(r, g, b)
                if a.format == "key" and v == key:
                    v ^= 0x0020  # never collide with the key by accident
                vals.append(v)
        out.append("static const uint16_t %s_data[] = {" % name)
        out.append(wrap(vals, 12, "0x%04X"))
        out.append("};")
        out.append("%sconst eccles_gui_image_t %s = {%s_data, %d, %d, %s, 0x%04X};" % (
            qual, name, name, w, h, "ECCLES_GUI_IMG_RGB565" if a.format == "rgb565" else "ECCLES_GUI_IMG_RGB565_KEY", key if a.format == "key" else 0))
    else:
        alpha = [p[3] if has_alpha else (p[0] * 299 + p[1] * 587 + p[2] * 114) // 1000 for p in px]
        if a.format == "a8":
            data = alpha
            fmt, enum = "0x%02X", "ECCLES_GUI_IMG_A8"
        elif a.format == "a4":
            data = []
            for y in range(h):
                row = [v >> 4 for v in alpha[y * w:(y + 1) * w]]
                if len(row) % 2:
                    row.append(0)
                data += [(row[i] << 4) | row[i + 1] for i in range(0, len(row), 2)]
            fmt, enum = "0x%02X", "ECCLES_GUI_IMG_A4"
        else:
            data = []
            for y in range(h):
                row = [1 if v >= a.threshold else 0 for v in alpha[y * w:(y + 1) * w]]
                while len(row) % 8:
                    row.append(0)
                for i in range(0, len(row), 8):
                    v = 0
                    for k in range(8):
                        v |= row[i + k] << (7 - k)
                    data.append(v)
            fmt, enum = "0x%02X", "ECCLES_GUI_IMG_A1"
        out.append("static const uint8_t %s_data[] = {" % name)
        out.append(wrap(data, 16, fmt))
        out.append("};")
        out.append("%sconst eccles_gui_image_t %s = {%s_data, %d, %d, %s, 0};" % (qual, name, name, w, h, enum))
    print("\n".join(out))


if __name__ == "__main__":
    main()
